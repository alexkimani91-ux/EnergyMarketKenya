"""Write results to CSV / Excel and a self-contained interactive HTML report."""
from __future__ import annotations

import html
from pathlib import Path

import pandas as pd

from . import charts


def export_dispatch(r, fin, out: Path):
    out.mkdir(parents=True, exist_ok=True)
    r.df("gen").to_csv(out / "hourly_generation_mw.csv")
    r.df("price").to_csv(out / "hourly_lmp_usd_mwh.csv")
    r.df("flow").to_csv(out / "hourly_line_flows_mw.csv")
    r.df("demand").to_csv(out / "hourly_demand_mw.csv")
    r.gen_by_tech().to_csv(out / "hourly_generation_by_tech_mw.csv")
    if len(r.reservoirs):
        r.df("s").div(1000).to_csv(out / "hourly_reservoir_gwh.csv")
    fin["plants"].to_csv(out / "plant_settlement.csv")
    fin["kpis"].to_csv(out / "kpis.csv", header=["value"])
    fin["tariff"].to_csv(out / "tariff_buildup_kes_kwh.csv", header=["KES/kWh"])
    with pd.ExcelWriter(out / "dispatch_results.xlsx") as xw:
        fin["kpis"].to_frame("value").to_excel(xw, sheet_name="KPIs")
        fin["tariff"].to_frame("KES/kWh").to_excel(xw, sheet_name="Tariff")
        fin["plants"].to_excel(xw, sheet_name="Plant settlement")
        if len(fin["storage"]):
            fin["storage"].to_excel(xw, sheet_name="Storage")
        (r.gen_by_tech() * r.dt / 1000).groupby(r.index.month).sum().to_excel(xw, sheet_name="Monthly GWh by tech")
        r.df("price").groupby(r.index.month).mean().to_excel(xw, sheet_name="Monthly avg LMP")


def export_expansion(x, out: Path):
    out.mkdir(parents=True, exist_ok=True)
    with pd.ExcelWriter(out / "expansion_results.xlsx") as xw:
        x["summary"].to_excel(xw, sheet_name="Summary")
        x["builds"].to_excel(xw, sheet_name="New builds MW")
        x["cumulative"].to_excel(xw, sheet_name="Cumulative new MW")
        x["capacity"].to_excel(xw, sheet_name="Capacity by tech MW")
        x["generation"].to_excel(xw, sheet_name="Generation by tech GWh")
    x["summary"].to_csv(out / "expansion_summary.csv")
    x["builds"].to_csv(out / "expansion_builds_mw.csv")


def _table(df, fmt="{:,.2f}"):
    return df.to_html(float_format=lambda v: fmt.format(v), border=0, classes="t")


def html_report(path: Path, title: str, r=None, fin=None, x=None, mc=None, mcs=None, cfg=None):
    figs, parts = [], []
    if fin is not None:
        k = fin["kpis"]
        parts.append("<h2>Key results - dispatch year</h2>" + _table(k.to_frame("value")))
        parts.append("<h2>Retail tariff build-up</h2>" + _table(fin["tariff"].to_frame("KES/kWh")))
    if r is not None:
        figs += [charts.dispatch_stack(r), charts.monthly_energy(r), charts.price_heatmap(r), charts.price_duration(r),
                 charts.reservoir_levels(r), charts.line_utilisation(r)]
    if fin is not None:
        figs += [charts.cost_breakdown(fin), charts.plant_economics_chart(fin), charts.tariff_waterfall(fin)]
        cols = ["tech", "capacity_mw", "generation_gwh", "capacity_factor", "curtailed_gwh", "total_cost_musd",
                "unit_cost_usd_mwh", "capture_price_usd_mwh", "co2_kt"]
        parts.append("<h2>Plant settlement</h2>" + _table(fin["plants"][cols]))
    if x is not None:
        figs += [charts.expansion_capacity(x), charts.expansion_builds(x), charts.expansion_generation(x),
                 charts.expansion_prices(x)]
        parts.append(f"<h2>Capacity expansion (NPV system cost {x['npv_cost_musd']:,.0f} MUSD)</h2>" + _table(x["summary"], "{:,.1f}"))
        b = x["builds"][x["builds"].sum(axis=1) > 0.5]
        parts.append("<h3>New builds (MW)</h3>" + _table(b, "{:,.0f}"))
    if mc is not None:
        figs += [charts.mc_hist(mc), charts.mc_scatter(mc)]
        parts.append(f"<h2>Monte Carlo risk analysis ({len(mc)} draws)</h2>" + _table(mcs))
    body = "".join(f.to_html(full_html=False, include_plotlyjs=(i == 0)) for i, f in enumerate(figs))
    css = """body{font-family:Segoe UI,Arial,sans-serif;max-width:1200px;margin:24px auto;padding:0 16px;color:#222}
    h1{color:#1B4F72} h2{border-bottom:2px solid #1B4F72;padding-bottom:4px;margin-top:32px}
    table.t{border-collapse:collapse;font-size:13px;margin:8px 0} .t th,.t td{padding:4px 10px;border-bottom:1px solid #ddd;text-align:right}
    .t th:first-child,.t td:first-child{text-align:left} .note{color:#666;font-size:13px}"""
    note = ("Indicative public-domain input data - replace with EPRA/KPLC/KenGen/KETRACO data before using for "
            "decisions. Generated by the Kenya Power Market Model (kpm).")
    doc = (f"<!doctype html><html><head><meta charset='utf-8'><title>{html.escape(title)}</title><style>{css}</style>"
           f"</head><body><h1>{html.escape(title)}</h1><p class='note'>{note}</p>{''.join(parts)}{body}</body></html>")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(doc, encoding="utf-8")
    return path
